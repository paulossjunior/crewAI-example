"""Create the secrets for the self-hosted Langfuse and point the app at it.

Writes ``infra/langfuse/.env`` (database/storage passwords, encryption keys, and the headless
initialization of an organization, a project with API keys and an admin user), then appends the
same project keys to the app's ``.env``. Both files are git-ignored. Safe to re-run: existing
files are never overwritten.

Run:  uv run python scripts/setup_langfuse_env.py
"""

from __future__ import annotations

import secrets
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGFUSE_ENV = ROOT / "infra" / "langfuse" / ".env"
APP_ENV = ROOT / ".env"
IMAGE_TAG = "4.87.0"  # same release as infra/langfuse/docker-compose.yml


def read_keys(env_file: Path) -> tuple[str, str]:
    values = dict(
        line.split("=", 1) for line in env_file.read_text().splitlines() if "=" in line and not line.startswith("#")
    )
    return values["LANGFUSE_INIT_PROJECT_PUBLIC_KEY"], values["LANGFUSE_INIT_PROJECT_SECRET_KEY"]


def main() -> None:
    if LANGFUSE_ENV.exists():
        print(f"{LANGFUSE_ENV.relative_to(ROOT)} já existe; mantendo.")
        public_key, secret_key = read_keys(LANGFUSE_ENV)
    else:
        public_key, secret_key = f"pk-lf-{uuid.uuid4()}", f"sk-lf-{uuid.uuid4()}"
        pg, ch, redis, minio = (secrets.token_urlsafe(18) for _ in range(4))
        password = secrets.token_urlsafe(12)
        LANGFUSE_ENV.write_text(f"""# Generated by scripts/setup_langfuse_env.py. NOT committed (see .gitignore).
LANGFUSE_IMAGE_TAG={IMAGE_TAG}
NEXTAUTH_URL=http://localhost:3000
NEXTAUTH_SECRET={secrets.token_hex(32)}
SALT={secrets.token_hex(16)}
ENCRYPTION_KEY={secrets.token_hex(32)}
POSTGRES_PASSWORD={pg}
DATABASE_URL=postgresql://postgres:{pg}@postgres:5432/postgres
CLICKHOUSE_PASSWORD={ch}
REDIS_AUTH={redis}
MINIO_ROOT_PASSWORD={minio}
LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY={minio}
LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY={minio}
LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY={minio}
# Headless initialization: organization, project, API keys and an admin user.
LANGFUSE_INIT_ORG_ID=dinner-crew-org
LANGFUSE_INIT_ORG_NAME=Dinner Crew
LANGFUSE_INIT_PROJECT_ID=dinner-crew
LANGFUSE_INIT_PROJECT_NAME=dinner-crew
LANGFUSE_INIT_PROJECT_PUBLIC_KEY={public_key}
LANGFUSE_INIT_PROJECT_SECRET_KEY={secret_key}
LANGFUSE_INIT_USER_EMAIL=admin@dinner-crew.local
LANGFUSE_INIT_USER_NAME=admin
LANGFUSE_INIT_USER_PASSWORD={password}
""")
        print(f"Criado {LANGFUSE_ENV.relative_to(ROOT)} (login: admin@dinner-crew.local / {password})")

    app_env = APP_ENV.read_text() if APP_ENV.exists() else ""
    if "LANGFUSE_PUBLIC_KEY" in app_env:
        print(".env já tem chaves do Langfuse; mantendo.")
        return
    APP_ENV.write_text(
        app_env.rstrip("\n")
        + f"\n\n# Local Langfuse (infra/langfuse)\nLANGFUSE_PUBLIC_KEY={public_key}\n"
        f"LANGFUSE_SECRET_KEY={secret_key}\nLANGFUSE_HOST=http://localhost:3000\n"
    )
    print("Chaves do Langfuse adicionadas ao .env")


if __name__ == "__main__":
    main()
